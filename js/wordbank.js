// (텍스트 모드에선 뜻이 명확히 다르므로 문제없음, 그림 모드에서만 생기는 혼동 방지)
const VISUAL_SIMILAR_GROUPS = [
  ['boy', 'girl', 'kid', 'child', 'baby'],
  ['man', 'woman'],
  ['grandma', 'grandpa'],
  ['son', 'daughter'],
  ['brother', 'sister'],
  ['uncle', 'aunt'],
  ['prince', 'princess'],
  ['king', 'queen'],
];
function isVisuallySimilar(wordA, wordB) {
  return VISUAL_SIMILAR_GROUPS.some(group => group.includes(wordA) && group.includes(wordB));
}

export function buildQuestionFromWord(targetWord) {
  const correctKorean = targetWord.korean;
  const g   = targetWord.group;
  const cat = targetWord.category;

  const tier = g <= 5 ? 1 : g <= 10 ? 2 : 3;

  const usedKoreans = new Set([correctKorean]);
  const distractors = [];       // 한국어 뜻 배열 (기존 로직 그대로 유지)
  const distractorWords = [];   // 영어 단어 배열 (이미지 매칭용, 같은 인덱스로 대응)

  // 공통 헬퍼: pool에서 조건 맞는 것 추가
  const tryAdd = (pool, opts = {}) => {
    const { sameCatOnly = false, similarityCheck = false, trapCheck = false } = opts;
    const shuffled = [...pool].sort(() => Math.random() - 0.5);
    for (const w of shuffled) {
      if (distractors.length >= 3) break;
      if (usedKoreans.has(w.korean)) continue;
      if (sameCatOnly && w.category !== cat) continue;
      if (similarityCheck && isTooSimilar(correctKorean, w.korean)) continue;
      if (tier === 1 && isVisuallySimilar(targetWord.word, w.word)) continue;
      distractors.push(w.korean);
      distractorWords.push(w.word);
      usedKoreans.add(w.korean);
    }
  };

  if (tier === 1) {
    // ── TIER 1 (GROUP 1~5): 같은 그룹 랜덤, 부족하면 전체 보충
    // (유사어 방지 체크 포함 — '빠른'/'재빠른' 동시 출현 방지)
    const sameGroup = WORD_BANK.filter(w => w.word !== targetWord.word && w.group === g);
    const allOther  = WORD_BANK.filter(w => w.word !== targetWord.word && w.group !== g);
    tryAdd(sameGroup, { similarityCheck: true });
    if (distractors.length < 3) tryAdd(allOther, { similarityCheck: true });
    if (distractors.length < 3) tryAdd(allOther);

  } else if (tier === 2) {
    // ── TIER 2 (GROUP 6~10): 같은 품사 필수 + 유사어 방지
    // 구성: 같은 품사 2개 + 다른 품사 1개 (같은 그룹 우선, 없으면 인접 그룹)
    const sameCatSameGroup  = WORD_BANK.filter(w => w.word !== targetWord.word && w.group === g   && w.category === cat);
    const sameCatNearGroup  = WORD_BANK.filter(w => w.word !== targetWord.word && Math.abs(w.group - g) <= 3 && w.group !== g && w.category === cat);
    const diffCatSameGroup  = WORD_BANK.filter(w => w.word !== targetWord.word && w.group === g   && w.category !== cat);
    const diffCatNearGroup  = WORD_BANK.filter(w => w.word !== targetWord.word && Math.abs(w.group - g) <= 3 && w.group !== g && w.category !== cat);
    const fallback           = WORD_BANK.filter(w => w.word !== targetWord.word);

    // 같은 품사 2개 먼저 (유사어 방지)
    tryAdd(sameCatSameGroup, { sameCatOnly: true, similarityCheck: true });
    tryAdd(sameCatNearGroup, { sameCatOnly: true, similarityCheck: true });
    // 나머지 1개는 다른 품사 (맥락 교란용)
    tryAdd(diffCatSameGroup);
    tryAdd(diffCatNearGroup);
    // 그래도 부족하면 전체 보충
    if (distractors.length < 3) tryAdd(fallback, { similarityCheck: true });

  } else {
    // ── TIER 3 (GROUP 11~15): 같은 품사 필수 + 함정 단어 적극 포함
    // 구성: 같은 품사 2개(의미 유사 함정 우선) + 같은 품사 1개(랜덤)
    const sameCatAll  = WORD_BANK.filter(w => w.word !== targetWord.word && w.category === cat);
    const fallback    = WORD_BANK.filter(w => w.word !== targetWord.word);

    // 함정 후보: TRAP_SEEDS에 정의된 뜻과 매칭되는 같은 품사 단어
    const trapKoreans = new Set();
    for (const [key, traps] of Object.entries(TRAP_SEEDS)) {
      if (correctKorean.includes(key)) {
        traps.forEach(t => trapKoreans.add(t));
      }
    }

    // 함정 단어 우선 추가 (같은 품사 중 TRAP_SEEDS 뜻과 일치하는 것)
    if (trapKoreans.size > 0) {
      const trapPool = sameCatAll.filter(w => [...trapKoreans].some(t => w.korean.includes(t)));
      tryAdd(trapPool, { sameCatOnly: true });
    }

    // 나머지는 같은 품사 + 유사어 방지로 채우기
    tryAdd(sameCatAll, { sameCatOnly: true, similarityCheck: true });

    // 그래도 부족하면 전체 보충
    if (distractors.length < 3) tryAdd(fallback, { similarityCheck: true });
  }

  // 4개 보기 섞기 (한국어 뜻 + 대응 영어 단어를 같은 순서로 섞음)
  const allKoreans = [correctKorean, ...distractors];
  const allWords    = [targetWord.word, ...distractorWords];
  const order = allKoreans.map((_, i) => i).sort(() => Math.random() - 0.5);
  const choices     = order.map(i => allKoreans[i]);
  const choiceWords = order.map(i => allWords[i]);
  const correctIndex = choices.indexOf(correctKorean);

  // TEST1(tier1)이고, 정답+오답 4개 전부 이미지가 준비된 경우에만 그림 선택형 가능
  const hasImages = tier === 1 && choiceWords.length === 4 &&
    choiceWords.every(w => IMAGE_WORDS.has(w));

  return {
    word:         targetWord.word,
    rank:         targetWord.rank,
    group:        targetWord.group,
    category:     targetWord.category,
    korean:       correctKorean,
    choices,
    choiceWords,
    correctIndex,
    hasImages,
  };
}
