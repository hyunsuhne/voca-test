// 의미상 너무 가까운 쌍 필터 (TIER 2~3 유사어 방지)
function isTooSimilar(k1, k2) {
  const similarGroups = [
    ['돈', '현금', '동전', '가격', '요금', '비용'],
    ['통증', '아픔', '부상', '상처', '다치다'],
    ['여행', '여행하다', '여정'],
    ['말하다', '이야기하다', '소리치다', '외치다', '속삭이다'],
    ['찾다', '탐색하다', '조사하다'],
    ['웃다', '낄낄 웃다', '미소 짓다'],
    ['걱정하다', '두려움', '무서움', '두려운'],
    ['시작하다', '시작'],
    ['끝내다', '끝'],
    ['(오븐에) 굽다', '(불에) 굽다', '(통째로) 굽다'],
    ['모으다', '수집하다', '한데 모이다'],
    ['훔치다', '빼앗다'],
    ['구조하다', '구하다', '보호하다'],
    ['흥미로운', '관심'],
  ];
  for (const g of similarGroups) {
    if (g.some(s => k1.includes(s)) && g.some(s => k2.includes(s))) return true;
  }
  if (k1.includes(k2) || k2.includes(k1)) return true;
  return false;
}

